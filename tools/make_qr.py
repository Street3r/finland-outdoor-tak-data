#!/usr/bin/env python3
"""Generate QR codes and SHARE.md from share/links.yaml.

Usage: python tools/make_qr.py          (requires: pip install segno pyyaml)
"""
from __future__ import annotations

from pathlib import Path
from urllib.parse import quote

import segno
import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "share" / "links.yaml"
QR_DIR = ROOT / "share" / "qr"
OUT_MD = ROOT / "SHARE.md"

ATAK_IMPORT = "tak://com.atakmap.app/import?url="


def target(entry: dict, base_url: str) -> tuple[str, str]:
    """Return (https url, QR payload)."""
    url = entry.get("url") or base_url.rstrip("/") + "/" + entry.get("path", "")
    if entry.get("kind", "import") == "import":
        return url, ATAK_IMPORT + quote(url, safe="")
    return url, url


def main() -> None:
    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    base_url = spec["base_url"]
    QR_DIR.mkdir(parents=True, exist_ok=True)
    wanted = set()

    groups: dict[str, list[str]] = {}
    for e in spec["links"]:
        url, payload = target(e, base_url)
        svg = QR_DIR / f"{e['id']}.svg"
        wanted.add(svg.name)
        segno.make(payload, error="m").save(svg, scale=4, border=3, dark="#000", light="#fff", xmldecl=False, svgclass=None, lineclass=None)
        kind = "Scan with the phone camera, open with ATAK" if payload != url else "Opens in a browser"
        note = f"<br>{e['note']}" if e.get("note") else ""
        groups.setdefault(e.get("group", "Links"), []).append(
            f"| <img src=\"share/qr/{svg.name}\" width=\"150\" alt=\"QR: {e['title']}\"> "
            f"| **{e['title']}**<br>{kind}{note}<br>[{url}]({url})"
            + (f"<br><sub><code>{payload}</code></sub>" if payload != url else "") + " |"
        )

    for old in QR_DIR.glob("*.svg"):  # remove QR codes of deleted entries
        if old.name not in wanted:
            old.unlink()

    lines = [
        "# Share",
        "",
        "<!-- Generated by tools/make_qr.py from share/links.yaml. Do not edit by hand. -->",
        "",
        "QR codes for ATAK: scan with the phone camera (or a QR app) and open with ATAK, which asks before importing. "
        "The `tak://` links only work on Android devices with ATAK; for iTAK and WinTAK use the https link.",
        "",
        "> **Suomeksi:** skannaa QR-koodi puhelimen kameralla ja avaa ATAKilla. iTAK ja WinTAK: käytä https-linkkiä.",
        "",
    ]
    for group, rows in groups.items():
        lines += [f"## {group}", "", "| QR | |", "|---|---|", *rows, ""]
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(wanted)} QR codes -> {QR_DIR.relative_to(ROOT)}, {OUT_MD.name}")


if __name__ == "__main__":
    main()
