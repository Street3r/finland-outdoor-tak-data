#!/usr/bin/env python3
"""Generate QR codes, SHARE.md (English) and SHARE.fi.md (Finnish) from share/links.yaml.

Usage: python tools/make_qr.py          (requires: pip install segno pyyaml)
"""
from __future__ import annotations

from pathlib import Path
from urllib.parse import quote

import segno
import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "share" / "links.yaml"
QR_DIR = ROOT / "share" / "qr"
ATAK_IMPORT = "tak://com.atakmap.app/import?url="

PAGES = {
    "en": {
        "file": "SHARE.md",
        "title": "Share",
        "other": "[Suomeksi](SHARE.fi.md)",
        "intro": "Scan a QR code with the phone camera and open it with ATAK; ATAK asks before importing. "
                 "`tak://` links work on Android with ATAK only. iTAK and WinTAK: use the https link.",
        "scan": "Scan with the phone camera, open with ATAK",
        "browser": "Opens in a browser",
    },
    "fi": {
        "file": "SHARE.fi.md",
        "title": "Jaa",
        "other": "[In English](SHARE.md)",
        "intro": "Skannaa QR-koodi puhelimen kameralla ja avaa ATAKilla; ATAK kysyy ennen tuontia. "
                 "`tak://`-linkit toimivat vain Androidilla ATAKissa. iTAK ja WinTAK: käytä https-linkkiä.",
        "scan": "Skannaa puhelimen kameralla, avaa ATAKilla",
        "browser": "Avautuu selaimessa",
    },
}


def target(entry: dict, base_url: str) -> tuple[str, str]:
    """Return (https url, QR payload)."""
    url = entry.get("url") or base_url.rstrip("/") + "/" + entry.get("path", "")
    if entry.get("kind", "import") == "import":
        return url, ATAK_IMPORT + quote(url, safe="")
    return url, url


def main() -> None:
    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    base_url = spec["base_url"]
    QR_DIR.mkdir(parents=True, exist_ok=True)
    wanted: set[str] = set()
    pages: dict[str, dict[str, list[str]]] = {lang: {} for lang in PAGES}

    for e in spec["links"]:
        url, payload = target(e, base_url)
        svg = QR_DIR / f"{e['id']}.svg"
        if svg.name not in wanted:
            segno.make(payload, error="m").save(svg, scale=4, border=3, dark="#000", light="#fff",
                                                xmldecl=False, svgclass=None, lineclass=None)
            wanted.add(svg.name)
        langs = list(PAGES) if e.get("lang", "all") == "all" else [e["lang"]]
        for lang in langs:
            t = PAGES[lang]
            how = t["scan"] if payload != url else t["browser"]
            note = f"<br>{e['note']}" if e.get("note") else ""
            uri = f"<br><sub><code>{payload}</code></sub>" if payload != url else ""
            pages[lang].setdefault(e.get("group", "Links"), []).append(
                f"| <img src=\"share/qr/{svg.name}\" width=\"150\" alt=\"QR: {e['title']}\"> "
                f"| **{e['title']}**<br>{how}{note}<br>[{url}]({url}){uri} |")

    for old in QR_DIR.glob("*.svg"):  # remove QR codes of deleted entries
        if old.name not in wanted:
            old.unlink()

    for lang, t in PAGES.items():
        lines = [f"# {t['title']}", "",
                 "<!-- Generated by tools/make_qr.py from share/links.yaml. Do not edit by hand. -->", "",
                 t["other"], "", t["intro"], ""]
        for group, rows in pages[lang].items():
            lines += [f"## {group}", "", "| QR | |", "|---|---|", *rows, ""]
        (ROOT / t["file"]).write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(wanted)} QR codes, " + ", ".join(t["file"] for t in PAGES.values()))


if __name__ == "__main__":
    main()
